"""Writes each project's trigger workflow, .github/workflows/project-<project>.yml, from one template.

  scaffold_workflows.py           write (or rewrite) the file for every project; remove files of deleted projects
  scaffold_workflows.py --check   fail if any project's file is missing, differs from the template, or is left over
                                  (run by ci.yml on every pull request)

The trigger only says WHEN a project is released (its own folder changed, a manual run) and in which environment
(the first one its project.yaml lists); the shared workflows _detect.yml and _stage.yml say WHAT and HOW. A run of
it shows two boxes: detect and the stage. GitHub reads workflows only from
.github/workflows/ (no subfolders), hence one generated file per project. Never edit them by hand.
"""
import glob
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKFLOWS = os.path.join(ROOT, ".github", "workflows")

TEMPLATE = """# GENERATED by scripts/scaffold_workflows.py from its template and projects/{project}/project.yaml: don't edit
# by hand. Releases project {project} (projects/{project}/) in its first environment, {env}:
#   pull request touching the project    plans and validation (nothing changes)
#   merge to main touching the project   tools, onboarding, agents in {env} (only what changed)
#   manual run                           everything, in {env}
# Promotion to the next environments (release tags v*) and shared-code changes: release-all.yml.
name: project {project}

on:
  push:
    branches: [main]
    paths: ["projects/{project}/**"]
  pull_request:
    paths: ["projects/{project}/**"]
  workflow_dispatch:

permissions:
  id-token: write
  contents: read

concurrency:
  group: release-{project}-${{{{ github.ref }}}}
  cancel-in-progress: false

jobs:
  detect:
    uses: ./.github/workflows/_detect.yml
    with:
      project: {project}

  {env}:
    needs: detect
    uses: ./.github/workflows/_stage.yml
    with:
      project: {project}
      environment: {env}
      tools: ${{{{ needs.detect.outputs.tools }}}}
      onboard: ${{{{ needs.detect.outputs.project }}}}
      agents: ${{{{ needs.detect.outputs.agents }}}}
      plan_only: ${{{{ github.event_name == 'pull_request' }}}}
"""


def first_environment(project):
    with open(os.path.join(ROOT, "projects", project, "project.yaml"), encoding="utf-8") as fh:
        return ((yaml.safe_load(fh) or {}).get("environments") or ["dev"])[0]


def wanted():
    projects = sorted(os.path.basename(os.path.dirname(f)) for f in glob.glob(os.path.join(ROOT, "projects", "*", "project.yaml")))
    return {os.path.join(WORKFLOWS, f"project-{p}.yml"): TEMPLATE.format(project=p, env=first_environment(p)) for p in projects}


def main(check):
    want = wanted()
    have = set(glob.glob(os.path.join(WORKFLOWS, "project-*.yml")))
    problems = []
    for path, text in want.items():
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            problems.append(f"{os.path.relpath(path, ROOT)}: {'missing' if current is None else 'differs from the template'}")
            if not check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
    for path in sorted(have - set(want)):
        problems.append(f"{os.path.relpath(path, ROOT)}: no such project")
        if not check:
            os.remove(path)
    if check and problems:
        sys.exit("Project trigger workflows are out of date (run python scripts/scaffold_workflows.py):\n  "
                 + "\n  ".join(problems))
    print("\n".join(problems) if problems else f"OK: {len(want)} project trigger workflow(s) up to date")


if __name__ == "__main__":
    main("--check" in sys.argv)
